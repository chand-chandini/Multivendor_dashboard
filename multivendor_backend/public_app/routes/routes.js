const express = require('express');
const router = express.Router();
const core = require('../lib/core');
const auth = require('../middleware/auth');
const controller = require('../controllers/publicCtrl');

router.use(core.tenant);
router.get('/bootstrap', controller.bootstrap);
router.get('/onboarding', controller.onboarding);
router.get('/app-updates', controller.appUpdates);
router.post('/auth/otp/request', controller.requestOtp);
router.post('/auth/otp/verify', controller.verifyOtp);
router.get('/home', controller.home);
router.get('/categories', controller.categories);
router.get('/categories/:categoryId/subcategories', controller.subcategories);
router.get('/restaurants', controller.restaurants);
router.get('/restaurants/:restaurantId', controller.restaurant);
router.get('/restaurants/:restaurantId/menu', controller.menu);
router.get('/locations', controller.locations);
router.get('/locations/serviceability', controller.serviceability);
router.get('/banners', controller.banners);
router.get('/search', controller.search);

router.use(auth.required);
router.get('/checkout/config', controller.checkoutConfig);
router.get('/me/delivery-slots', controller.deliverySlots);
router.get('/me', controller.me);
router.put('/me', controller.updateMe);
router.post('/auth/logout', controller.logout);
router.post('/me/account-deletion-requests', controller.deleteAccount);
router.get('/me/notifications', controller.notifications);
router.post('/me/notifications/read', controller.markNotificationsRead);
router.get('/me/addresses', controller.addresses);
router.post('/me/addresses', controller.createAddress);
router.put('/me/addresses/:addressId', controller.updateAddress);
router.delete('/me/addresses/:addressId', controller.deleteAddress);
router.put('/me/addresses/:addressId/default', controller.defaultAddress);
router.get('/me/cart', controller.cart);
router.post('/me/cart/items', controller.addCartItem);
router.put('/me/cart/items/:itemId', controller.updateCartItem);
router.delete('/me/cart/items/:itemId', controller.deleteCartItem);
router.delete('/me/cart', controller.clearCart);
router.get('/coupons', controller.coupons);
router.post('/coupons/validate', controller.validateCoupon);
router.get('/me/orders', controller.orders);
router.post('/orders', controller.createOrder);
router.get('/orders/:orderId', controller.order);
router.post('/orders/:orderId/review', controller.orderReview);
router.get('/orders/:orderId/tracking', controller.orderTracking);
router.get('/me/favourites', controller.favourites);
router.put('/me/favourites/:type/:targetId', controller.saveFavourite);
router.delete('/me/favourites/:type/:targetId', controller.deleteFavourite);

router.use(core.errorHandler);
module.exports = router;
